async function main() {
  console.log("Seeding question bank (One-Word, MCQ, and Typing)...");

  // Clean existing questions
  await prisma.question.deleteMany({});

  const allQuestions = [...oneWordQuestions, ...mcqQuestions, ...typingPassages];

  for (const q of allQuestions) {
    await prisma.question.create({
      data: {
        language: q.language,
        duelType: q.duelType,
        question: q.question,
        correctAnswer: q.correctAnswer,
        acceptedAliases: q.acceptedAliases,
        options: q.options,
        difficulty: q.difficulty,
      },
    });
  }

  const oneWordCount = await prisma.question.count({ where: { duelType: "ONE_WORD" } });
  const mcqCount = await prisma.question.count({ where: { duelType: "MCQ" } });
  const typingCount = await prisma.question.count({ where: { duelType: "TYPING" } });
  const total = await prisma.question.count();

  console.log(`Successfully seeded ${total} total questions!`);
  console.log(`- One-Word Questions: ${oneWordCount} (32 C++, 32 Java, 32 Python)`);
  console.log(`- MCQ Questions: ${mcqCount} (32 C++, 32 Java, 32 Python)`);
  console.log(`- Typing Passages: ${typingCount} (8 C++, 8 Java, 8 Python)`);
}

main()
  .catch((e) => {
    console.error("Error seeding questions:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
